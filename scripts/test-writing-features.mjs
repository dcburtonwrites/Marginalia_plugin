import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.MARGINALIA_PLAYWRIGHT||'playwright');
const browser=await chromium.launch({headless:true});
try {
 for (const theme of ['light','dark']) {
  const context=await browser.newContext({viewport:{width:1280,height:900}});
  const page=await context.newPage(), errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(pathToFileURL(resolve('.preview/scripts.html')).href+`?editor&studio&theme=${theme}`);
  await page.getByRole('combobox',{name:'Project or grouping'}).selectOption({label:'Copper Sky > Draft'});
  await page.locator('#sidebar').getByRole('button',{name:'Opening',exact:true}).click();
  await page.getByLabel('Script editor').waitFor();
  const before=await page.evaluate(()=>window.mobileEditor.text());
  assert.equal(await page.locator('.marginalia-writing-focus').count(),0);
  await page.getByRole('button',{name:'Writing settings',exact:true}).click();
  await page.getByLabel('Focused writing',{exact:true}).check();
  await page.getByLabel('Record session history',{exact:true}).check();
  await page.getByRole('button',{name:'Close settings'}).click();
  assert.equal(await page.locator('.marginalia-writing-focus').count(),1);
  assert.ok(await page.locator('.marginalia-focus-paragraph').count());
  assert.equal(await page.evaluate(()=>window.mobileEditor.text()),before);
  await page.getByLabel('Script editor').click();
  await page.keyboard.press('ArrowDown');
  await page.screenshot({path:resolve(`design/verification/writing-focus-${theme}.png`)});
  await page.getByRole('button',{name:'Writing settings',exact:true}).click();
  await page.getByLabel('Focused writing',{exact:true}).uncheck();
  assert.equal(await page.locator('.marginalia-writing-focus').count(),0);
  await page.getByLabel('Focused writing',{exact:true}).check();
  await page.getByRole('button',{name:'Close settings'}).click();
  await page.getByRole('button',{name:'Start timer',exact:true}).click();
  await page.evaluate(()=>window.mobileEditor.set(window.mobileEditor.text()+'\n\nNew words here.'));
  await page.getByRole('button',{name:'Pause timer',exact:true}).click();
  await page.getByRole('button',{name:'Reset timer',exact:true}).click();
  await page.getByRole('button',{name:'History & progress',exact:true}).click();
  await page.getByRole('heading',{name:'Writing history',exact:true}).waitFor();
  const row=page.locator('.marginalia-history-table tbody tr');
  assert.equal(await row.count(),1);
  assert.match(await row.textContent(),/Draft/);
  assert.match(await row.textContent(),/stopped/);
  assert.equal(await row.locator('td').nth(3).textContent(),'3');
  await page.getByRole('button',{name:'Export CSV',exact:true}).click();
  await page.getByRole('button',{name:'Clear history',exact:true}).click();
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  assert.equal(await row.count(),1);
  await page.screenshot({path:resolve(`design/verification/writing-features-${theme}.png`)});
  await page.reload();
  await page.getByRole('button',{name:'History & progress',exact:true}).click();
  assert.equal(await page.locator('.marginalia-history-table tbody tr').count(),1);
  await page.getByRole('button',{name:'Clear history',exact:true}).click();
  await page.getByRole('button',{name:'Clear saved history',exact:true}).click();
  await page.getByRole('button',{name:'History & progress',exact:true}).click();
  assert.equal(await page.locator('.marginalia-history-table tbody tr').count(),0);
  assert.deepEqual(errors,[]);
  await context.close();
 }
 console.log('Writing features: light/dark focus, source preservation, timer history, word totals, CSV, clear cancellation and reload passed.');
} finally { await browser.close(); }
