import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium,devices}=require(process.env.MARGINALIA_PLAYWRIGHT||'playwright');
const browser=await chromium.launch({headless:true});
try {
 for(const [name,device] of [['phone',devices['iPhone 13']],['tablet',devices['iPad Mini']]]){
  const context=await browser.newContext({...device});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(pathToFileURL(resolve('.preview/scripts.html')).href+'?mobile&studio');
  await page.getByRole('combobox',{name:'Project or grouping'}).selectOption({label:'Copper Sky > Draft'});
  await page.getByRole('button',{name:'Compile PDF…',exact:true}).click();
  const dialog=page.getByRole('dialog'),preview=dialog.getByRole('button',{name:'Preview script',exact:true});
  await dialog.getByRole('heading',{name:'Content Selections',exact:true}).waitFor();
  assert.equal(await dialog.getByRole('combobox',{name:'Preset',exact:true}).count(),0);
  for(const label of [/^Panel Descriptions/,'Callouts and Notes','Title page'])assert.ok(await dialog.getByRole('checkbox',{name:label}).isChecked());
  assert.ok(await preview.isDisabled(),'title page requires an author');
  const author=dialog.getByRole('textbox',{name:'Author name',exact:true});
  await author.fill('Alex Writer');
  assert.equal(await preview.isDisabled(),false);
  assert.equal(await dialog.getByRole('alert').isVisible(),false,'empty warning must have no orange border');
  await dialog.getByRole('checkbox',{name:'Title page',exact:true}).uncheck();
  assert.ok(!await author.isVisible());
  await dialog.getByRole('checkbox',{name:'Title page',exact:true}).check();
  assert.equal(await author.inputValue(),'Alex Writer');
  await dialog.getByRole('checkbox',{name:/^Panel Descriptions/}).uncheck();
  await dialog.getByText('Included scripts ·',{exact:false}).click();
  const checks=dialog.locator('details').first().getByRole('checkbox');
  const included=await checks.count();assert.ok(included>=2);
  for(let i=0;i<included;i++)await checks.nth(i).uncheck();
  assert.ok(await preview.isDisabled());
  await checks.first().check();
  await dialog.getByText('Advanced',{exact:true}).click();
  await dialog.getByRole('combobox',{name:'Paper',exact:true}).selectOption('A4');
  await preview.click();
  await page.getByText('Script preview · PDF export is available on desktop.',{exact:true}).waitFor();
  assert.ok(await page.getByRole('button',{name:'Export PDF…',exact:true}).isDisabled());
  await page.locator('.marginalia-compile-document article').waitFor();
  assert.equal(await page.locator('.marginalia-compile-document article').count(),1);
  const cover=page.locator('.marginalia-compile-cover');
  assert.equal(await cover.count(),1);
  assert.match(await cover.textContent(),/By Alex Writer/);
  const localDate=await page.evaluate(()=>new Intl.DateTimeFormat(undefined,{year:'numeric',month:'long',day:'numeric'}).format(new Date()));
  assert.ok((await cover.textContent()).includes('Draft · '+localDate));
  await page.getByRole('button',{name:'Compile options…',exact:true}).click();
  assert.equal(await author.inputValue(),'Alex Writer');
  await dialog.getByText('Advanced',{exact:true}).click();
  assert.equal(await dialog.getByRole('combobox',{name:'Paper',exact:true}).inputValue(),'A4');
  await dialog.getByRole('combobox',{name:'Group',exact:true}).selectOption('Revision');
  assert.equal(await author.inputValue(),'Alex Writer','author is shared across Groups in this vault');
  for(const label of [/^Panel Descriptions/,'Callouts and Notes','Title page'])assert.ok(await dialog.getByRole('checkbox',{name:label}).isChecked());
  await author.fill('Second Writer');await preview.click();
  await page.locator('.marginalia-compile-byline').getByText('By Second Writer',{exact:true}).waitFor();
  await page.reload();
  await page.getByRole('button',{name:'Compile PDF…',exact:true}).click();
  await author.waitFor();
  assert.equal(await author.inputValue(),'Second Writer');
  assert.equal(await dialog.getByRole('checkbox',{name:/^Panel Descriptions/}).isChecked(),false,'saved Group choices are preserved');
  await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
  assert.deepEqual(errors,[],name+' browser errors');
  console.log(name+': content defaults, empty-warning removal, author validation/toggle, dated byline, cross-Group name changes and reload passed');
  await context.close();
 }
 const page=await browser.newPage();
 await page.goto(pathToFileURL(resolve('.preview/scripts.html')).href+'?studio');
 await page.getByRole('combobox',{name:'Project or grouping'}).selectOption({label:'Copper Sky > Draft'});
 await page.getByRole('button',{name:'Compile PDF…',exact:true}).click();
 await page.getByRole('textbox',{name:'Author name',exact:true}).fill('Alex Writer');
 await page.getByRole('button',{name:'Preview PDF',exact:true}).click();
 await page.getByText('This Obsidian desktop host does not expose the local PDF print engine.',{exact:true}).waitFor();
 assert.ok(await page.getByRole('button',{name:'Export PDF…',exact:true}).isDisabled());
 assert.ok(await page.locator('.marginalia-compile-document article').count());
 console.log('desktop without print capability: readable preview, explanation and disabled export passed');
} finally {await browser.close();}
